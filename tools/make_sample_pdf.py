def resolve_font() -> str:
    for path in FONT_CANDIDATES:
        if Path(path).exists():
            pdfmetrics.registerFont(TTFont("Body", path))
            return "Body"
    sys.exit("Не найден TTF со кириллицей, поправь FONT_CANDIDATES")


def main() -> None:
    font = resolve_font()
    out = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "sample_tender.pdf"
    out.parent.mkdir(parents=True, exist_ok=True)

    pdf = canvas.Canvas(str(out), pagesize=A4)
    width, height = A4
    for lines in PAGES:
        pdf.setFont(font, 11)
        y = height - 60
        for line in lines:
            pdf.drawString(50, y, line)
            y -= 18
        pdf.showPage()
    pdf.save()
    print(f"Готово: {out}")


if __name__ == "__main__":
    main()
